# Rebuild the checked-in, offline Kotlin element table from authoritative sources.
# Scientific values are data, not instructions. No remote executable is downloaded.
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$sourceDirectory = Join-Path $root '.cache\reference-source'
New-Item -ItemType Directory -Force -Path $sourceDirectory | Out-Null
$pubchemPath = Join-Path $sourceDirectory 'pubchem-elements.json'
$ciaawPath = Join-Path $sourceDirectory 'ciaaw-weights.html'
Invoke-WebRequest -UseBasicParsing -Uri 'https://pubchem.ncbi.nlm.nih.gov/rest/pug/periodictable/JSON' -OutFile $pubchemPath -TimeoutSec 60
Invoke-WebRequest -UseBasicParsing -Uri 'https://ciaaw.org/abridged-atomic-weights.htm' -OutFile $ciaawPath -TimeoutSec 60
$pubchem = Get-Content -LiteralPath $pubchemPath -Raw | ConvertFrom-Json
$html = Get-Content -LiteralPath $ciaawPath -Raw
$weights = @{}
foreach ($row in [regex]::Matches($html, '<tr><td>(\d+)</td><td>([A-Za-z]+)</td><td>.*?</td><td>(.*?)</td>')) {
    $value = [System.Net.WebUtility]::HtmlDecode(($row.Groups[3].Value -replace '<[^>]+>', '')).Trim()
    if ($value -match '^([0-9.]+)') { $weights[$row.Groups[2].Value] = $Matches[1] }
}
if ($pubchem.Table.Row.Count -ne 118 -or $weights.Count -lt 80) { throw 'Unexpected element source format.' }
$names = '氢 氦 锂 铍 硼 碳 氮 氧 氟 氖 钠 镁 铝 硅 磷 硫 氯 氩 钾 钙 钪 钛 钒 铬 锰 铁 钴 镍 铜 锌 镓 锗 砷 硒 溴 氪 铷 锶 钇 锆 铌 钼 锝 钌 铑 钯 银 镉 铟 锡 锑 碲 碘 氙 铯 钡 镧 铈 镨 钕 钷 钐 铕 钆 铽 镝 钬 铒 铥 镱 镥 铪 钽 钨 铼 锇 铱 铂 金 汞 铊 铅 铋 钋 砹 氡 钫 镭 锕 钍 镤 铀 镎 钚 镅 锔 锫 锎 锿 镄 钔 锘 铹 𬬻 𬭊 𬭳 𬭛 𬭶 鿏 𫟼 𬬭 鿔 鿭 𫓧 镆 𫟷 鿬 鿫'.Split(' ')
if ($names.Count -ne 118) { throw 'Chinese element name mapping must contain 118 entries.' }
$categories = @{'Nonmetal'='非金属';'Noble gas'='稀有气体';'Alkali metal'='碱金属';'Alkaline earth metal'='碱土金属';'Metalloid'='类金属';'Halogen'='卤素';'Transition metal'='过渡金属';'Post-transition metal'='后过渡金属';'Lanthanide'='镧系';'Actinide'='锕系'}
function Quoted([string]$value) {
    if ([string]::IsNullOrWhiteSpace($value)) { return 'null' }
    return '"' + $value.Replace('\', '\\').Replace('"', '\"').Replace('$', '\$').Replace("`r", '').Replace("`n", '\n') + '"'
}
function NumberLiteral([string]$value) {
    if ([string]::IsNullOrWhiteSpace($value)) { return 'null' }
    $number = 0.0
    if (-not [double]::TryParse($value, [System.Globalization.NumberStyles]::Float, [System.Globalization.CultureInfo]::InvariantCulture, [ref]$number)) { throw "Invalid numeric value: $value" }
    if ($value -notmatch '[.Ee]') { return "$value.0" }
    return $value
}
$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('// Generated by scripts/update-elements.ps1. Sources and units: docs/DATA_SOURCES.md.')
$lines.Add('package com.titradeck.app.chemistry')
$lines.Add('')
$lines.Add('data class Element(')
$lines.Add('    val atomicNumber: Int, val symbol: String, val name: String, val englishName: String,')
$lines.Add('    val atomicMass: Double, val group: Int?, val period: Int, val category: String,')
$lines.Add('    val electronConfiguration: String?, val electronegativity: Double?, val atomicRadius: Double?,')
$lines.Add('    val meltingPoint: Double?, val boilingPoint: Double?, val oxidationStates: String?,')
$lines.Add('    val massIsRepresentative: Boolean,')
$lines.Add(') {')
$lines.Add('    val displayColumn: Int get() = when (atomicNumber) { in 57..71 -> atomicNumber - 54; in 89..103 -> atomicNumber - 86; else -> group ?: 3 }')
$lines.Add('    val displayRow: Int get() = when (atomicNumber) { in 57..71 -> 8; in 89..103 -> 9; else -> period }')
$lines.Add('    val source: String get() = "https://pubchem.ncbi.nlm.nih.gov/periodic-table/"')
$lines.Add('    val massSource: String get() = if (massIsRepresentative) source else "https://ciaaw.org/abridged-atomic-weights.htm"')
$lines.Add('}')
$lines.Add('')
$lines.Add('object Elements {')
$lines.Add('    val all: List<Element> = listOf(')
foreach ($row in $pubchem.Table.Row) {
    $c = $row.Cell
    $number = [int]$c[0]
    $symbol = [string]$c[1]
    $period = if ($number -le 2) {1} elseif ($number -le 10) {2} elseif ($number -le 18) {3} elseif ($number -le 36) {4} elseif ($number -le 54) {5} elseif ($number -le 86) {6} else {7}
    $group = if ($number -eq 1) {'1'} elseif ($number -eq 2) {'18'} elseif ($number -le 10) {if ($number -le 4) {[string]($number-2)} else {[string]($number+8)}} elseif ($number -le 18) {if ($number -le 12) {[string]($number-10)} else {[string]$number}} elseif ($number -le 36) {[string]($number-18)} elseif ($number -le 54) {[string]($number-36)} elseif ($number -le 56) {[string]($number-54)} elseif ($number -le 71) {'null'} elseif ($number -le 86) {[string]($number-68)} elseif ($number -le 88) {[string]($number-86)} elseif ($number -le 103) {'null'} else {[string]($number-100)}
    $representative = -not $weights.ContainsKey($symbol)
    $mass = if ($representative) {$c[3]} else {$weights[$symbol]}
    $category = if ($categories.ContainsKey([string]$c[15])) {$categories[[string]$c[15]]} else {$c[15]}
    $args = @([string]$number,(Quoted $symbol),(Quoted $names[$number-1]),(Quoted $c[2]),(NumberLiteral $mass),$group,[string]$period,(Quoted $category),(Quoted $c[5]),(NumberLiteral $c[6]),(NumberLiteral $c[7]),(NumberLiteral $c[12]),(NumberLiteral $c[13]),(Quoted $c[10]),([string]$representative).ToLowerInvariant())
    $lines.Add('        Element(' + ($args -join ', ') + '),')
}
$lines.Add('    )')
$lines.Add('    val bySymbol: Map<String, Element> = all.associateBy { it.symbol }')
$lines.Add('}')
$outputDirectory = Join-Path $root 'app\src\main\java\com\titradeck\app\chemistry'
New-Item -ItemType Directory -Force -Path $outputDirectory | Out-Null
[System.IO.File]::WriteAllLines((Join-Path $outputDirectory 'Elements.kt'), $lines, [System.Text.UTF8Encoding]::new($false))
Write-Output "Generated 118 elements; $($weights.Count) CIAAW standard atomic weights."
